CREATE TABLE IF NOT EXISTS incidents (
    id              VARCHAR(40) PRIMARY KEY,
    idempotency_key VARCHAR(100) UNIQUE,
    service         VARCHAR(60)  NOT NULL,
    report_json     CLOB         NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS runs (
    id                    VARCHAR(40) PRIMARY KEY,
    incident_id           VARCHAR(40) NOT NULL REFERENCES incidents (id),
    service               VARCHAR(60) NOT NULL,
    status                VARCHAR(30) NOT NULL,
    stage                 VARCHAR(30),
    version               INT         NOT NULL,
    fix_attempts          INT         NOT NULL,
    correction_rounds     INT         NOT NULL,
    classification_json   CLOB,
    rca_json              CLOB,
    mitigation_json       CLOB,
    patch_json            CLOB,
    patch_sha256          VARCHAR(64),
    validation_json       CLOB,
    fix_feedback          CLOB,
    publish_json          CLOB,
    approved_by           VARCHAR(60),
    approved_patch_sha256 VARCHAR(64),
    failure_reason        VARCHAR(1000),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Evidence timeline: every item records which tool call produced it and a hash of the raw tool output.
CREATE TABLE IF NOT EXISTS evidence (
    run_id         VARCHAR(40)  NOT NULL REFERENCES runs (id),
    evidence_id    VARCHAR(10)  NOT NULL,
    kind           VARCHAR(30)  NOT NULL,
    source_tool    VARCHAR(40)  NOT NULL,
    tool_call_id   VARCHAR(40),
    observed_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    content_sha256 VARCHAR(64)  NOT NULL,
    summary        CLOB         NOT NULL,
    flags          VARCHAR(200) NOT NULL,
    PRIMARY KEY (run_id, evidence_id)
);

CREATE TABLE IF NOT EXISTS run_timeline (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id  VARCHAR(40)   NOT NULL,
    at      TIMESTAMP WITH TIME ZONE NOT NULL,
    stage   VARCHAR(30),
    kind    VARCHAR(20)   NOT NULL,
    message VARCHAR(2000) NOT NULL
);

CREATE TABLE IF NOT EXISTS tool_calls (
    call_id       VARCHAR(40) PRIMARY KEY,
    run_id        VARCHAR(40) NOT NULL,
    stage         VARCHAR(30) NOT NULL,
    actor         VARCHAR(40) NOT NULL,
    tool          VARCHAR(80) NOT NULL,
    args_sha256   VARCHAR(64) NOT NULL,
    decision      VARCHAR(20) NOT NULL,
    reason        VARCHAR(500),
    latency_ms    BIGINT      NOT NULL,
    result_sha256 VARCHAR(64),
    result_chars  INT         NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Prompts are not stored or logged; only their hash and size, for audit and cost tracking.
CREATE TABLE IF NOT EXISTS model_calls (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        VARCHAR(40) NOT NULL,
    stage         VARCHAR(30) NOT NULL,
    actor         VARCHAR(40) NOT NULL,
    provider      VARCHAR(40) NOT NULL,
    model         VARCHAR(60) NOT NULL,
    turn          INT         NOT NULL,
    prompt_sha256 VARCHAR(64) NOT NULL,
    input_chars   INT         NOT NULL,
    output_chars  INT         NOT NULL,
    input_tokens  BIGINT      NOT NULL,
    output_tokens BIGINT      NOT NULL,
    outcome       VARCHAR(30) NOT NULL,
    latency_ms    BIGINT      NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS review_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       VARCHAR(40)   NOT NULL,
    actor        VARCHAR(60)   NOT NULL,
    action       VARCHAR(20)   NOT NULL,
    comment      VARCHAR(2000),
    patch_sha256 VARCHAR(64),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Redelivery safety: a command id is recorded in the same transaction as the state change it caused.
CREATE TABLE IF NOT EXISTS processed_commands (
    command_id   VARCHAR(40) PRIMARY KEY,
    run_id       VARCHAR(40) NOT NULL,
    stage        VARCHAR(30) NOT NULL,
    outcome      VARCHAR(20) NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Transactional outbox: the next command is written atomically with the state change, then relayed.
CREATE TABLE IF NOT EXISTS command_outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_id   VARCHAR(40) NOT NULL UNIQUE,
    run_id       VARCHAR(40) NOT NULL,
    payload      CLOB        NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts     INT         NOT NULL
);

CREATE TABLE IF NOT EXISTS dead_letters (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      VARCHAR(40),
    reason      VARCHAR(1000) NOT NULL,
    payload_sha256 VARCHAR(64) NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL
);
